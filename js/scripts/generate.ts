/**
 * Regenerate `src/generated/` from every schema at the repository root.
 *
 * Two files are produced: `types.ts`, the TypeScript types derived with
 * json-schema-to-typescript from the latest manifest schema and the latest
 * geometry schema, and `schema.ts`, every schema object itself as a
 * constant, so that the package bundles the schemas without a JSON import.
 * The test suite re-runs this module and fails when the committed files
 * differ from a fresh generation.
 *
 *     node scripts/generate.ts
 */

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));

export const schemaDirectory = resolve(here, "../../schema");
export const generatedDirectory = resolve(here, "../src/generated");

const SCHEMA_FILE = /^timeskeleton-(\d+)\.(\d+)\.(\d+)\.schema\.json$/;
const GEOMETRY_FILE = /^geometry-(\d+)\.(\d+)\.(\d+)\.schema\.json$/;

/** Keep the schema file names among `names`, ordered by parsed version (0.2.0 before 0.10.0). */
export function orderSchemaFiles(names: readonly string[], pattern = SCHEMA_FILE): string[] {
  return names
    .map((name) => ({ name, match: pattern.exec(name) }))
    .filter((entry): entry is { name: string; match: RegExpExecArray } => entry.match !== null)
    .map(({ name, match }) => ({ name, version: match.slice(1, 4).map(Number) }))
    .sort((a, b) => {
      for (let i = 0; i < 3; i += 1) {
        const difference = (a.version[i] ?? 0) - (b.version[i] ?? 0);
        if (difference !== 0) {
          return difference;
        }
      }
      return 0;
    })
    .map(({ name }) => name);
}

/** Return the schema file names at the repository root, ordered by parsed version. */
export function schemaFileNames(): string[] {
  return orderSchemaFiles(readdirSync(schemaDirectory));
}

/** Return the geometry schema file names at the repository root, ordered by parsed version. */
export function geometryFileNames(): string[] {
  return orderSchemaFiles(readdirSync(schemaDirectory), GEOMETRY_FILE);
}

/** Return the path of the schema file with the highest version. */
export function latestSchemaPath(): string {
  const latest = schemaFileNames().at(-1);
  if (latest === undefined) {
    throw new Error(`no schema file in ${schemaDirectory}`);
  }
  return resolve(schemaDirectory, latest);
}

function banner(schemaFile: string): string {
  return `// Generated by scripts/generate.ts from schema/${schemaFile}. Do not edit.`;
}

/** Render the TypeScript types for the latest manifest and geometry schemas. */
export async function renderTypes(
  schemaText: string,
  schemaFile: string,
  geometryText?: string,
): Promise<string> {
  return compile(schemaForTypes(schemaText, geometryText), "TimeSkeletonManifest", {
    bannerComment: banner(schemaFile),
    additionalProperties: true,
    declareExternallyReferenced: true,
    unreachableDefinitions: true,
  });
}

/**
 * Convert 2020-12 tuple notation for the generator's older tuple reader, and
 * join the geometry schema to the manifest schema.
 *
 * The emitted schemas keep the source documents unchanged. This compatibility
 * view affects only TypeScript generation: `prefixItems` would otherwise
 * become `never[]` instead of a two-item tuple. The geometry schema's
 * definitions, and its root as `Geometry`, join the manifest schema's
 * definitions (the names are disjoint), its references into the manifest
 * schema become local ones, and the open union `Primitive` becomes the union
 * of its known kinds, so that both share one set of types.
 */
function schemaForTypes(schemaText: string, geometryText?: string): object {
  const schema = JSON.parse(schemaText) as { $id: string; $defs: Record<string, unknown> };
  if (geometryText !== undefined) {
    const sourceGeometry = JSON.parse(geometryText) as { $id: string };
    const external = `${sourceGeometry.$id.replace("/geometry.schema.json", "/timeskeleton.schema.json")}#/$defs/`;
    const geometry = JSON.parse(geometryText.replaceAll(external, "#/$defs/")) as Record<
      string,
      unknown
    > & { $defs: Record<string, unknown> };
    const { $defs: definitions, $schema: _, $id: __, title: ___, ...root } = geometry;
    const primitive = definitions.Primitive as { allOf: { then: object }[] };
    Object.assign(schema.$defs, definitions, {
      Geometry: root,
      Primitive: { anyOf: primitive.allOf.map((branch) => branch.then) },
    });
  }

  function visit(value: unknown): void {
    if (Array.isArray(value)) {
      value.forEach(visit);
      return;
    }
    if (typeof value !== "object" || value === null) {
      return;
    }
    const node = value as Record<string, unknown>;
    Object.values(node).forEach(visit);
    if (Array.isArray(node.prefixItems) && node.items === false) {
      node.items = node.prefixItems;
      node.additionalItems = false;
      delete node.prefixItems;
    }
  }

  visit(schema);
  return schema as object;
}

/** Render all schema objects, keyed by declared schema version. */
export function renderSchema(
  schemas: readonly { text: string; file: string }[],
  geometries: readonly { text: string; file: string }[] = [],
): string {
  const entries = schemas.map(({ text }) => {
    const parsed = JSON.parse(text) as {
      properties: { meta: { properties: { schema_version: { const: string } } } };
    };
    return [parsed.properties.meta.properties.schema_version.const, parsed] as const;
  });
  const latest = entries.at(-1);
  if (latest === undefined) throw new Error("no schema files");
  const json = JSON.stringify(Object.fromEntries(entries), null, 2);
  const geometryEntries = geometries.map(({ text }) => {
    const parsed = JSON.parse(text) as {
      properties: { meta: { properties: { schema_version: { const: string } } } };
    };
    return [parsed.properties.meta.properties.schema_version.const, parsed] as const;
  });
  const latestGeometry = geometryEntries.at(-1);
  if (latestGeometry === undefined) throw new Error("no geometry schema files");
  const geometryJson = JSON.stringify(Object.fromEntries(geometryEntries), null, 2);
  return `${banner(schemas.at(-1)?.file ?? "")}\nexport const schemas = ${json} as const;\nexport const schema = schemas[${JSON.stringify(latest[0])}];\nexport const geometrySchemas = ${geometryJson} as const;\nexport const geometrySchema = geometrySchemas[${JSON.stringify(latestGeometry[0])}];\n`;
}

/** Produce both generated files for the latest schema, keyed by file name. */
export async function generate(): Promise<Record<string, string>> {
  const schemaPath = latestSchemaPath();
  const schemaFile = schemaPath.slice(schemaDirectory.length + 1);
  const schemaText = readFileSync(schemaPath, "utf8");
  const read = (file: string) => ({
    file,
    text: readFileSync(resolve(schemaDirectory, file), "utf8"),
  });
  const schemas = schemaFileNames().map(read);
  const geometries = geometryFileNames().map(read);
  const geometry = geometries.at(-1);
  return {
    "types.ts": await renderTypes(schemaText, schemaFile, geometry?.text),
    "schema.ts": renderSchema(schemas, geometries),
  };
}

async function main(): Promise<void> {
  mkdirSync(generatedDirectory, { recursive: true });
  for (const [name, content] of Object.entries(await generate())) {
    writeFileSync(resolve(generatedDirectory, name), content);
    console.log(`wrote src/generated/${name}`);
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
