/**
 * Regenerate `src/generated/` from every schema at the repository root.
 *
 * A schema version is either one file, `schema/timeskeleton-<version>.schema.json`
 * (0.5.0 and 0.6.0, the timeline file only), or a directory `schema/<version>/`
 * holding the documents `core`, `timeline`, `group` and `bundle` as
 * `<name>.schema.json`, which refer to each other by relative `$ref`.
 *
 * Three files are produced: `types.ts`, the TypeScript types derived with
 * json-schema-to-typescript from the documents of the latest version;
 * `schema.ts`, every schema document itself as a constant, so that the package
 * bundles the schemas without a JSON import; and `font.ts`, the metrics of the
 * bundled font (`fonts/dejavu-sans-2.37.metrics.json`) as a constant.
 * The test suite re-runs this module and fails when the committed files
 * differ from a fresh generation.
 *
 *     node scripts/generate.ts
 */

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));

export const schemaDirectory = resolve(here, "../../schema");
export const generatedDirectory = resolve(here, "../src/generated");
const metricsPath = resolve(here, "../../fonts/dejavu-sans-2.37.metrics.json");

const SCHEMA_FILE = /^timeskeleton-(\d+)\.(\d+)\.(\d+)\.schema\.json$/;
const VERSION_DIRECTORY = /^(\d+)\.(\d+)\.(\d+)$/;

/** The documents of a version with a directory, in the order they are bundled. */
export const DOCUMENTS = ["core", "timeline", "group", "bundle"] as const;

/** The names a file kind's root type takes in `types.ts`, keyed by document. */
const ROOT_TYPES: Readonly<Record<string, string>> = {
  timeline: "TimeSkeletonManifest",
  group: "TimeSkeletonGroupFile",
  bundle: "TimeSkeletonBundleFile",
};

function versionOf(name: string): number[] | null {
  const match = SCHEMA_FILE.exec(name) ?? VERSION_DIRECTORY.exec(name);
  return match === null ? null : match.slice(1, 4).map(Number);
}

/**
 * Keep the schema entries among `names` (single schema files and version
 * directory names), ordered by parsed version (0.9.0 before 0.10.0).
 */
export function orderSchemaFiles(names: readonly string[]): string[] {
  return names
    .map((name) => ({ name, version: versionOf(name) }))
    .filter((entry): entry is { name: string; version: number[] } => entry.version !== null)
    .sort((a, b) => {
      for (let i = 0; i < 3; i += 1) {
        const difference = (a.version[i] ?? 0) - (b.version[i] ?? 0);
        if (difference !== 0) {
          return difference;
        }
      }
      return 0;
    })
    .map(({ name }) => name);
}

/** One schema version: its documents' paths relative to `schema/`, keyed by name. */
export interface SchemaVersion {
  readonly version: string;
  readonly documents: Readonly<Record<string, string>>;
}

/** Return every schema version at the repository root, ordered by parsed version. */
export function schemaVersions(): SchemaVersion[] {
  return orderSchemaFiles(readdirSync(schemaDirectory)).map((name) => {
    const version = (versionOf(name) as number[]).join(".");
    if (!statSync(resolve(schemaDirectory, name)).isDirectory()) {
      return { version, documents: { timeline: name } };
    }
    return {
      version,
      documents: Object.fromEntries(DOCUMENTS.map((doc) => [doc, `${name}/${doc}.schema.json`])),
    };
  });
}

function readDocument(path: string): Record<string, unknown> {
  return JSON.parse(readFileSync(resolve(schemaDirectory, path), "utf8")) as Record<
    string,
    unknown
  >;
}

function banner(source: string): string {
  return `// Generated by scripts/generate.ts from schema/${source}. Do not edit.`;
}

/** Where a version's schema lies, as named in the banners. */
function sourceOf(version: SchemaVersion): string {
  const documents = Object.values(version.documents);
  return documents.length === 1 ? (documents[0] as string) : `${version.version}/`;
}

/**
 * Render the TypeScript types for the documents of one version.
 *
 * The documents are compiled as one schema: the timeline document's root is
 * `TimeSkeletonManifest`, the group and bundle documents' roots join the
 * definitions as `TimeSkeletonGroupFile` and `TimeSkeletonBundleFile`, every
 * definition of every document joins under its own name (names are unique
 * across a version's documents), and every reference becomes local.
 */
export async function renderTypes(version: SchemaVersion): Promise<string> {
  const documents = Object.fromEntries(
    Object.entries(version.documents).map(([name, path]) => [name, readDocument(path)]),
  );
  const root = documents.timeline as Record<string, unknown>;
  const definitions: Record<string, unknown> = {};
  for (const [name, document] of Object.entries(documents)) {
    Object.assign(definitions, document.$defs as Record<string, unknown>);
    const rootType = ROOT_TYPES[name];
    if (name !== "timeline" && rootType !== undefined) {
      const { $schema: _, $id: __, $defs: ___, ...fileRoot } = document;
      definitions[rootType] = { ...fileRoot, title: rootType };
    }
  }
  const combined = { ...root, title: ROOT_TYPES.timeline, $defs: definitions };
  return compile(schemaForTypes(combined), "TimeSkeletonManifest", {
    bannerComment: banner(sourceOf(version)),
    additionalProperties: true,
    declareExternallyReferenced: true,
    unreachableDefinitions: true,
  });
}

/**
 * Prepare a schema for the generator.
 *
 * The emitted schemas keep the source documents unchanged. This view affects
 * only TypeScript generation: a reference into another document of the same
 * version (`core.schema.json#/$defs/Id`) becomes local (`#/$defs/Id`), and
 * 2020-12 tuple notation is converted for the generator's older tuple reader,
 * as `prefixItems` would otherwise become `never[]` instead of a two-item
 * tuple.
 */
function schemaForTypes(schema: object): object {
  const view = JSON.parse(JSON.stringify(schema)) as object;

  function visit(value: unknown): void {
    if (Array.isArray(value)) {
      value.forEach(visit);
      return;
    }
    if (typeof value !== "object" || value === null) {
      return;
    }
    const node = value as Record<string, unknown>;
    Object.values(node).forEach(visit);
    if (typeof node.$ref === "string") {
      node.$ref = node.$ref.replace(/^[a-z]+\.schema\.json#/, "#");
    }
    if (Array.isArray(node.prefixItems) && node.items === false) {
      node.items = node.prefixItems;
      node.additionalItems = false;
      delete node.prefixItems;
    }
  }

  visit(view);
  return view;
}

/**
 * Render every schema document, keyed by version and document name
 * (`schemaDocuments`), every version's timeline document keyed by version
 * (`schemas`) and the latest one (`schema`).
 */
export function renderSchema(versions: readonly SchemaVersion[]): string {
  const latest = versions.at(-1);
  if (latest === undefined) throw new Error("no schema files");
  const documents = Object.fromEntries(
    versions.map(({ version, documents }) => [
      version,
      Object.fromEntries(
        Object.entries(documents).map(([name, path]) => [name, readDocument(path)]),
      ),
    ]),
  );
  const json = JSON.stringify(documents, null, 2);
  const timelines = versions
    .map(
      ({ version }) =>
        `  ${JSON.stringify(version)}: schemaDocuments[${JSON.stringify(version)}].timeline,`,
    )
    .join("\n");
  return `${banner(sourceOf(latest))}\nexport const schemaDocuments = ${json} as const;\nexport const schemas = {\n${timelines}\n} as const;\nexport const schema = schemas[${JSON.stringify(latest.version)}];\n`;
}

/** Render the metrics of the bundled font as a typed constant. */
export function renderFont(metricsText: string): string {
  const banner =
    "// Generated by scripts/generate.ts from fonts/dejavu-sans-2.37.metrics.json. Do not edit.";
  const json = JSON.stringify(JSON.parse(metricsText));
  return `${banner}\nimport type { FontMetrics } from "../font.js";\n\nexport const fontMetrics: FontMetrics = ${json};\n`;
}

/** Produce the generated files, keyed by file name. */
export async function generate(): Promise<Record<string, string>> {
  const versions = schemaVersions();
  const latest = versions.at(-1);
  if (latest === undefined) throw new Error(`no schema in ${schemaDirectory}`);
  return {
    "types.ts": await renderTypes(latest),
    "schema.ts": renderSchema(versions),
    "font.ts": renderFont(readFileSync(metricsPath, "utf8")),
  };
}

async function main(): Promise<void> {
  mkdirSync(generatedDirectory, { recursive: true });
  for (const [name, content] of Object.entries(await generate())) {
    writeFileSync(resolve(generatedDirectory, name), content);
    console.log(`wrote src/generated/${name}`);
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
