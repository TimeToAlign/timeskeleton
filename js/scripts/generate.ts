/**
 * Regenerate `src/generated/` from the schema at the repository root.
 *
 * The repository holds one schema version, a directory `schema/<version>/`
 * with the one document `timeskeleton.schema.json`.
 *
 * Three files are produced: `types.ts`, the TypeScript types derived with
 * json-schema-to-typescript from the document; `schema.ts`, the document
 * itself as a constant, so that the package bundles the schema without a JSON
 * import; and `font.ts`, the metrics of the bundled font
 * (`fonts/dejavu-sans-2.37.metrics.json`) as a constant. The test suite
 * re-runs this module and fails when the committed files differ from a fresh
 * generation.
 *
 *     node scripts/generate.ts
 */

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));

export const schemaDirectory = resolve(here, "../../schema");
export const generatedDirectory = resolve(here, "../src/generated");
const metricsPath = resolve(here, "../../fonts/dejavu-sans-2.37.metrics.json");

const VERSION_DIRECTORY = /^\d+\.\d+\.\d+$/;

/** The name of the schema document inside its version directory. */
export const DOCUMENT = "timeskeleton.schema.json";

/**
 * Return the path of the schema document relative to `schema/`: the one
 * version directory's `timeskeleton.schema.json`.
 *
 * @throws {Error} unless `schema/` holds exactly one version directory.
 */
export function schemaSource(): string {
  const versions = readdirSync(schemaDirectory).filter(
    (name) =>
      VERSION_DIRECTORY.test(name) && statSync(resolve(schemaDirectory, name)).isDirectory(),
  );
  if (versions.length !== 1) {
    throw new Error(`expected one schema version in ${schemaDirectory}, found ${versions.length}`);
  }
  return `${versions[0]}/${DOCUMENT}`;
}

function readDocument(path: string): Record<string, unknown> {
  return JSON.parse(readFileSync(resolve(schemaDirectory, path), "utf8")) as Record<
    string,
    unknown
  >;
}

function banner(source: string): string {
  return `// Generated by scripts/generate.ts from schema/${source}. Do not edit.`;
}

/**
 * Render the TypeScript types of the schema document.
 *
 * The root type is `TimeSkeleton`, and every definition joins under its own
 * name. Objects take only their declared properties
 * (`additionalProperties: false` for generation), so a misspelt key is a
 * compile error, while the free objects (`meta`, `metric_hierarchy`), which
 * declare `additionalProperties: true`, stay free.
 */
export async function renderTypes(source: string): Promise<string> {
  const document = readDocument(source);
  const definitions = { ...(document.$defs as Record<string, Record<string, unknown>>) };
  const { TimeSkeleton: root, ...rest } = definitions;
  if (root === undefined) throw new Error("the schema defines no TimeSkeleton");
  const view = { ...root, title: "TimeSkeleton", $defs: rest };
  return compile(schemaForTypes(view), "TimeSkeleton", {
    bannerComment: banner(source),
    additionalProperties: false,
    declareExternallyReferenced: true,
    unreachableDefinitions: true,
  });
}

type Node = Record<string, unknown>;

/**
 * Prepare a schema for the generator.
 *
 * The emitted schema keeps the source document unchanged. This view affects
 * only TypeScript generation:
 *
 * - conditionals (`if`, `then`, `else`), the unknown-key annotation
 *   (`unevaluatedProperties`) and an `anyOf` whose branches only require
 *   members are removed, as the generator cannot express them, and so are
 *   defaults, which would make it copy a referenced definition;
 * - an object whose `oneOf` branches narrow its own properties (a
 *   coordinate's value by its number type) becomes a union of whole objects;
 * - a reference that also requires members (a child timeline requiring its
 *   offset) becomes the referenced type intersected with those members;
 * - 2020-12 tuple notation is converted for the generator's older tuple
 *   reader, as `prefixItems` would otherwise become `never[]` instead of a
 *   two-item tuple.
 */
function schemaForTypes(schema: Node): Node {
  const view = JSON.parse(JSON.stringify(schema)) as Node;
  const definitions = (view.$defs ?? {}) as Record<string, Node>;
  const onlyRequires = (branch: unknown) =>
    typeof branch === "object" && branch !== null && Object.keys(branch).join() === "required";

  function visit(value: unknown): void {
    if (Array.isArray(value)) {
      value.forEach(visit);
      return;
    }
    if (typeof value !== "object" || value === null) {
      return;
    }
    const node = value as Node;
    for (const keyword of ["if", "then", "else", "unevaluatedProperties", "default"]) {
      delete node[keyword];
    }
    if (Array.isArray(node.anyOf) && node.anyOf.every(onlyRequires)) delete node.anyOf;
    if (
      typeof node.properties === "object" &&
      Array.isArray(node.oneOf) &&
      node.oneOf.every((branch: Node) => !("$ref" in branch))
    ) {
      const shared = node.properties as Node;
      const required = node.required;
      node.oneOf = node.oneOf.map((branch: Node) => ({
        ...branch,
        type: "object",
        properties: { ...shared, ...(branch.properties as Node) },
        required,
      }));
      for (const keyword of ["type", "properties", "required", "discriminator"]) {
        delete node[keyword];
      }
    }
    if (typeof node.$ref === "string" && Array.isArray(node.required)) {
      const target = definitions[node.$ref.replace("#/$defs/", "")] ?? {};
      const properties = (target.properties ?? {}) as Node;
      const members = node.required as string[];
      node.allOf = [
        { $ref: node.$ref },
        {
          type: "object",
          properties: Object.fromEntries(members.map((member) => [member, properties[member]])),
          required: members,
        },
      ];
      delete node.$ref;
      delete node.required;
    }
    Object.values(node).forEach(visit);
    if (Array.isArray(node.prefixItems) && node.items === false) {
      node.items = node.prefixItems;
      node.additionalItems = false;
      delete node.prefixItems;
    }
  }

  visit(view);
  return view;
}

/** Render the schema document as the constant `schema`. */
export function renderSchema(source: string): string {
  const json = JSON.stringify(readDocument(source), null, 2);
  return `${banner(source)}\nexport const schema = ${json} as const;\n`;
}

/** Render the metrics of the bundled font as a typed constant. */
export function renderFont(metricsText: string): string {
  const banner =
    "// Generated by scripts/generate.ts from fonts/dejavu-sans-2.37.metrics.json. Do not edit.";
  const json = JSON.stringify(JSON.parse(metricsText));
  return `${banner}\nimport type { FontMetrics } from "../font.js";\n\nexport const fontMetrics: FontMetrics = ${json};\n`;
}

/** Produce the generated files, keyed by file name. */
export async function generate(): Promise<Record<string, string>> {
  const source = schemaSource();
  return {
    "types.ts": await renderTypes(source),
    "schema.ts": renderSchema(source),
    "font.ts": renderFont(readFileSync(metricsPath, "utf8")),
  };
}

async function main(): Promise<void> {
  mkdirSync(generatedDirectory, { recursive: true });
  for (const [name, content] of Object.entries(await generate())) {
    writeFileSync(resolve(generatedDirectory, name), content);
    console.log(`wrote src/generated/${name}`);
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
